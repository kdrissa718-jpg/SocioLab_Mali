export function getTranslationValue(translationsObject, language, key) {
  const fallbackLanguage = language === "en" ? "fr" : "en";
  const value = key.split(".").reduce((current, part) => current?.[part], translationsObject[language]) ?? key;
  if (value !== key) return value;
  const fallbackValue = key.split(".").reduce((current, part) => current?.[part], translationsObject[fallbackLanguage]) ?? key;
  return fallbackValue;
}
